/* Literal dialogue editor codec. Never normalizes unchanged SOURCE LOCK lines. */
(function(root,factory){
 "use strict";
 const api=factory();
 if(typeof module==="object"&&module.exports)module.exports=api;
 root.ComicDialogueCodec=api;
})(typeof globalThis==="object"?globalThis:this,function(){
 "use strict";
 const clone=x=>JSON.parse(JSON.stringify(x));
 function assertLines(lines){
  if(!Array.isArray(lines)||!lines.every(l=>l&&typeof l.speaker==="string"&&
    typeof l.target==="string"&&typeof l.text==="string"))throw Error("セリフの構造が不正です");
 }
 function format(lines){
  assertLines(lines);
  return lines.map(l=>l.speaker+" | "+l.target+" | "+l.text).join("\n");
 }
 function parse(raw){
  if(typeof raw!=="string")throw Error("セリフ入力の形式が不正です");
  if(raw.length>120000)throw Error("セリフ入力が長すぎます");
  return raw.replace(/\r\n/g,"\n").split("\n").filter(x=>x.trim()).map((row,n)=>{
    const first=row.indexOf("|"),second=row.indexOf("|",first+1);
    if(first<0||second<0)throw Error("セリフの"+(n+1)+"行目は「話者ID | 相手ID | 本文」の形式にしてください");
    const speaker=row.slice(0,first).trim(),target=row.slice(first+1,second).trim();
    // Exactly one separator space is generated by format(). Preserve all others.
    const text=row.slice(second+1).replace(/^ /,"");
    if(!speaker||!text.trim())throw Error("セリフの"+(n+1)+"行目は話者と本文が必要です");
    return {speaker,target,text};
  });
 }
 function retainOrParse(raw,original){
  assertLines(original);
  if(raw===format(original))return clone(original);
  return parse(raw);
 }
 return Object.freeze({format,parse,retainOrParse});
});