'use strict';
/**
 * Read-only post-generation handoff for a single externally supplied candidate.
 * It cannot start paid generation. All outputs remain in review/quarantine.
 * It deliberately reuses the existing dry-run preflight before touching candidate data.
 */
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const cp=require('node:child_process');
const {runMockPanel,inspectPng}=require('./offline-render-pipeline.cjs');
const {assessResult}=require('./retry-controller.cjs');
const {validateCandidate}=require('./page-gate.cjs');

function reject(reason,detail={}){
 return {status:'QUARANTINED',reason,artApproved:false,
   canonApproved:false,publicationApproved:false,providerCalled:false,...detail};
}
function ingestOfflineCandidate(args={}){
 const {imageBytes,expectedOutput='single_panel',...preflightInputs}=args;
 if(!['single_panel','page'].includes(expectedOutput))
   return reject('UNKNOWN_OUTPUT_CONTRACT');
 // Explicitly refuse paid/external provider mode; ingest already generated bytes only.
 if(preflightInputs.renderMode&&preflightInputs.renderMode!=='mock')
   return reject('NETWORK_GENERATION_DISABLED');
 const pre=runMockPanel({...preflightInputs,renderMode:'mock'});
 if(pre.status!=='MOCK_ONLY_NOT_ART')
   return reject('PRE_GENERATION_NOT_CLEAR',{preflightReason:pre.reason,
     preflightIssues:pre.preflight?.issues||pre.retry?.issues||pre.issues||[]});
 if(!Buffer.isBuffer(imageBytes)||imageBytes.length>24*1024*1024||
    imageBytes.length<33)
   return reject('IMAGE_MISSING_OR_INVALID');
 let actual;
 try{actual=inspectPng(imageBytes);}
 catch(e){return reject('IMAGE_PNG_HEADER_INVALID',{detail:String(e.message)});}
 // Run the native, pixel-decoding structure gate in a disposable temp directory.
 // An unsafe or unsupported image is held, never passed to image editing.
 let tmp;
 let layout;
 try{
   tmp=fs.mkdtempSync(path.join(os.tmpdir(),'mirror-handoff-'));
   const input=path.join(tmp,'untrusted.png');
   fs.writeFileSync(input,imageBytes,{mode:0o600,flag:'wx'});
   const tool=path.join(__dirname,'panel_output_gate.py');
   const run=cp.spawnSync('python3',[tool,input,'--expected',expectedOutput],{
     encoding:'utf8',timeout:20000,maxBuffer:64*1024
   });
   if(run.error||![0,2].includes(run.status))
     return reject('STRUCTURE_INSPECTION_FAILED',{
       dimension:{width:actual.width,height:actual.height},sha256:actual.sha256
     });
   try{layout=JSON.parse(run.stdout);}
   catch{return reject('STRUCTURE_REPORT_INVALID');}
   if(layout.sha256!==actual.sha256||layout.width!==actual.width||
      layout.height!==actual.height||layout.expected!==expectedOutput)
     return reject('STRUCTURE_REPORT_NOT_BOUND_TO_BYTES');
 }catch(e){return reject('STRUCTURE_INSPECTION_EXCEPTION',{detail:String(e.message)});}
 finally{if(tmp)fs.rmSync(tmp,{recursive:true,force:true});}
 const lock={...JSON.parse(preflightInputs.sourceBytes.toString('utf8')),
   sha256:pre.lockSha256};
 const candidate={
   pageId:lock.pageId,panelId:preflightInputs.panelId,
   sourceLockSha256:pre.lockSha256,inputSha256:pre.inputSha256,
   sha256:actual.sha256,outputSha256:actual.sha256,
   width:actual.width,height:actual.height,
   renderProvenance:'external-candidate-unverified'
 };
 const history=Array.isArray(preflightInputs.history)?preflightInputs.history:[];
 // The 2048x3072 threshold belongs to an assembled PAGE, not a single panel.
 // A panel remains review-only until face/dialogue/bubbles and target detail are checked.
 const independentQA=expectedOutput==='page'?
    assessResult({sourceLockSha256:pre.lockSha256,history,candidate,verifiedQA:null}):
    {status:'REVIEW_REQUIRED',issues:[
      {code:'PANEL_VISUAL_QA_REQUIRED',
       reason:'顔・セリフ・吹き出し尻尾・ネイティブ画質の実画像QAを実施'}
    ]};
 const wholePageQA=expectedOutput==='page'?
   validateCandidate({lock,candidate,review:null}):null;
 const quarantine=layout.status==='BLOCKED';
 return {
   status:quarantine?'QUARANTINED':'REVIEW_REQUIRED',
   reason:quarantine?layout.reason:'STRUCTURE_ONLY_PASSED_EDITORIAL_QA_REQUIRED',
   expectedOutput,providerCalled:false,
   sourceLockSha256:pre.lockSha256,inputSha256:pre.inputSha256,
   image:{sha256:actual.sha256,width:actual.width,height:actual.height},
   structure:layout,
   independentQA:{status:independentQA.status,
     issues:independentQA.issues},
   wholePageQA:wholePageQA?{status:wholePageQA.status,
     issues:wholePageQA.issues}:null,
   safeToAddAsFinishedArtwork:false,
   artApproved:false,canonApproved:false,publicationApproved:false,
   // Approved art is immutable: no image file is copied, overwritten or moved here.
   originalImageUnchanged:true,
   note:'構造検査の通過は顔・文字・コマの合格ではない。公開不可。'
 };
}
module.exports={ingestOfflineCandidate};
